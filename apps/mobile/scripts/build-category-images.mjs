// Generates src/lib/category-images.ts: a static require() map of the bundled category artwork,
// keyed by taxonomy slug path (e.g. 'mobile/electronics', 'electronics/air-conditioners').
// Re-run after adding/removing files under assets/categories/explore/.
// Usage: node scripts/build-category-images.mjs
import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ASSET_DIR = path.join(appRoot, 'assets/categories/explore');
const TARGET = path.join(appRoot, 'src/lib/category-images.ts');
const IMG = /\.(webp|png|jpe?g)$/i;

const keys = [];
(function scan(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) scan(full);
    else if (IMG.test(entry.name)) {
      const rel = path.relative(ASSET_DIR, full).split(path.sep).join('/');
      keys.push(rel.replace(IMG, ''));
    }
  }
})(ASSET_DIR);

keys.sort();
const q = (s) => JSON.stringify(s);
const lines = keys
  .map((k) => `  ${q(k)}: require('../../assets/categories/explore/${k}.webp'),`)
  .join('\n');

writeFileSync(
  TARGET,
  `/* eslint-disable @typescript-eslint/no-require-imports */
// GENERATED by scripts/build-category-images.mjs - do not edit.
// Bundled category artwork keyed by taxonomy slug path; render via lookupCategoryImage().
import type { ImageSourcePropType } from 'react-native';

const CATEGORY_IMAGES: Record<string, ImageSourcePropType> = {
${lines}
};

/** Returns the bundled image for a taxonomy slug path, or undefined to fall back to a placeholder. */
export function lookupCategoryImage(key: string | undefined): ImageSourcePropType | undefined {
  return key ? CATEGORY_IMAGES[key] : undefined;
}
`,
);
console.log(`Wrote ${path.relative(appRoot, TARGET)} with ${keys.length} images.`);
