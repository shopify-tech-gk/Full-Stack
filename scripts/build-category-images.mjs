// Builds apps/mobile/src/lib/category-images.ts - the app's bundled category artwork - from the
// files under apps/mobile/assets/categories/explore/, keyed by taxonomy slug path:
//   mobile/<main>.webp | <main>/<sub>.webp | <main>/<sub>/<sub-to-sub>.webp
// React Native can only bundle images through static require() calls, hence the generated map.
// Usage: pnpm build:category-images - after adding or replacing images in that folder.
import { execFileSync } from 'node:child_process';
import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const IMAGE_DIR = path.join(root, 'apps/mobile/assets/categories/explore');
const TARGET = path.join(root, 'apps/mobile/src/lib/category-images.ts');
const IMAGE_EXT = /\.(webp|png|jpe?g)$/i;

const keys = [];
(function scan(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) scan(full);
    else if (IMAGE_EXT.test(entry.name)) {
      keys.push(path.relative(IMAGE_DIR, full).split(path.sep).join('/'));
    }
  }
})(IMAGE_DIR);
keys.sort();

const q = (s) => JSON.stringify(s);
const lines = keys
  .map(
    (rel) =>
      `  ${q(rel.replace(IMAGE_EXT, ''))}: require('../../assets/categories/explore/${rel}'),`,
  )
  .join('\n');

writeFileSync(
  TARGET,
  `/* eslint-disable @typescript-eslint/no-require-imports */
// GENERATED by scripts/build-category-images.mjs - do not edit.
// Bundled category artwork keyed by taxonomy slug path; render via lookupCategoryImage().
import type { ImageSourcePropType } from 'react-native';

const CATEGORY_IMAGES: Record<string, ImageSourcePropType> = {
${lines}
};

/** Returns the bundled image for a taxonomy slug path, or undefined to fall back to a placeholder. */
export function lookupCategoryImage(key: string | undefined): number | undefined {
  return key ? (CATEGORY_IMAGES[key] as number | undefined) : undefined;
}
`,
);
// Keep the file byte-identical to what lint/prettier would produce.
execFileSync(
  process.execPath,
  [path.join(root, 'node_modules/prettier/bin/prettier.cjs'), '--write', TARGET],
  { stdio: 'ignore' },
);
console.log(`Wrote ${path.relative(root, TARGET)}: ${keys.length} images`);
