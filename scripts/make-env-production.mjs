// Builds deploy/.env.production.example from .env.example: every variable kept (with its comments),
// hosts pointed at the Docker service names, production settings applied, and EVERY secret
// replaced by CHANGE_ME. Re-run after adding variables to .env.example:
//   node scripts/make-env-production.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(path.join(root, '.env.example'), 'utf8');

// Port -> Docker Compose service name (deploy/docker-compose.prod.yml).
const HOST_BY_PORT = {
  4000: 'gateway', 4001: 'auth', 4002: 'catalog', 4003: 'inventory', 4004: 'cart', 4005: 'order',
  4006: 'payment', 4007: 'seller', 4008: 'settlement', 4009: 'logistics', 4010: 'returns',
  4011: 'address', 4012: 'notification', 4013: 'search', 4014: 'invoice', 4015: 'admin',
};

// Values set outright for production.
const SET = {
  POSTGRES_USER: 'youmart',
  POSTGRES_DB: 'youmart',
  POSTGRES_PORT: '5432',
  // Inside Docker the gateway must listen beyond loopback (only Caddy is published to the world).
  GATEWAY_HOST: '0.0.0.0',
  REDIS_HOST: 'redis',
  REDIS_URL: 'redis://redis:6379',
  TYPESENSE_HOST: 'typesense',
  COOKIE_SECURE: 'true',
  COOKIE_DOMAIN: '',
  STOREFRONT_URL: 'https://youmart.in',
  CDN_BASE_URL: 'https://youmart.in/api',
  CORS_ALLOWED_ORIGINS: 'https://youmart.in,https://www.youmart.in',
  RATE_LIMIT_MAX: '300',
  NOTIFICATIONS_ENABLED: 'true',
  EMAIL_SENDING_ENABLED: 'true',
  INVOICE_STORAGE_DIR: './storage/invoices',
};

// Anything that looks secret becomes CHANGE_ME (never ship a dev value to production).
const SECRET = /(PASSWORD|SECRET|_KEY$|KEY_ID$|TOKEN|PRIVATE|AUTH_KEY|CLIENT_ID|CLIENT_SECRET|HASH)/;

const out = [];
for (const line of src.split(/\r?\n/)) {
  const m = /^([A-Z0-9_]+)=(.*)$/.exec(line);
  if (!m) {
    out.push(line);
    continue;
  }
  const [, key, raw] = m;
  let value = raw;
  if (key in SET) value = SET[key];
  else if (/_DATABASE_URL$|^DATABASE_URL$/.test(key)) {
    // postgresql://user:pw@localhost:5433/db?schema=x -> user:CHANGE_ME@postgres:5432/youmart
    value = raw
      .replace(/:\/\/([^:]+):[^@]*@/, '://$1:CHANGE_ME@')
      .replace(/@localhost:\d+\//, '@postgres:5432/')
      .replace(/\/youmart_dev\?/, '/youmart?');
    if (key === 'DATABASE_URL') value = value.replace(/:\/\/[^:]+:/, '://youmart:');
  } else if (/^http:\/\/localhost:(\d+)/.test(raw)) {
    const port = Number(/^http:\/\/localhost:(\d+)/.exec(raw)[1]);
    const host = HOST_BY_PORT[port];
    if (host) value = raw.replace(/^http:\/\/localhost:\d+/, `http://${host}:${port}`);
  } else if (SECRET.test(key) && raw !== '' && !/^(true|false|\d+)$/.test(raw)) {
    value = 'CHANGE_ME';
  }
  out.push(`${key}=${value}`);
}

const header = `# YouMart PRODUCTION environment - copy to /opt/youmart/.env on the server and fill in every
# CHANGE_ME (generated by scripts/make-env-production.mjs from .env.example; never commit the
# filled-in copy). Hosts are the Docker service names from deploy/docker-compose.prod.yml.

# --- deployment (read by docker compose / Caddy / deploy.sh) ---
SITE_DOMAIN=youmart.in
BACKEND_IMAGE=ghcr.io/CHANGE_ME/youmart-backend
WEB_IMAGE=ghcr.io/CHANGE_ME/youmart-web
# Set by deploy.sh to the commit being deployed.
IMAGE_TAG=latest
# Proxy hops in front: Cloudflare -> Caddy -> gateway -> services.
GATEWAY_TRUSTED_PROXY_HOPS=1
ADMIN_TRUSTED_PROXY_HOPS=2
TRUSTED_PROXY_HOPS=2
LOG_LEVEL=warn
# Inside Docker the gateway listens beyond loopback (only Caddy is published to the world).
GATEWAY_HOST=0.0.0.0
# Nightly database backup target (deploy/server/backup.sh; uses the instance's IAM role).
BACKUP_S3_URI=s3://CHANGE_ME-youmart-backups/postgres
TYPESENSE_HOST=typesense

`;
writeFileSync(path.join(root, 'deploy', '.env.production.example'), header + out.join('\n'));
console.log('wrote deploy/.env.production.example');
