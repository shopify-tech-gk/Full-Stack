// Builds apps/notification-service/src/assistant/category-index.data.ts - the YouMart AI's searchable
// list of store categories - from the same sheet as the app's taxonomy
// (packages/shared-client/data/category-taxonomy.csv). Usage: pnpm build:assistant-categories,
// after the sheet changes (build:category-taxonomy runs it too).
//
// Each entry's `taxo` is the app's taxonomy path ("main~sub~leaf", slugs exactly as
// buildCategoryTaxonomy makes them), so a category the AI shows opens the same category screen as
// tapping it in the app.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(root, 'packages/shared-client/data/category-taxonomy.csv');
const TARGET = path.join(root, 'apps/notification-service/src/assistant/category-index.data.ts');

/** RFC 4180: quoted fields may hold commas, doubled quotes and newlines. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') {
        field += '"';
        i += 1;
      } else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') {
      row.push(field);
      field = '';
    } else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i += 1;
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else field += ch;
  }
  if (field || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => r.some((c) => c.trim()));
}

/** Same as shared-client's slugify (categories.ts). */
const slugify = (value) =>
  value
    .toLowerCase()
    .replace(/&/g, ' ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

const [, ...rows] = parseCsv(readFileSync(SOURCE, 'utf8'));
/** taxo -> [taxo, name, parent trail] */
const entries = new Map();
for (const [mainRaw, subRaw, itemRaw] of rows) {
  const main = mainRaw.trim();
  const sub = subRaw.trim();
  const item = (itemRaw ?? '').trim();
  if (!main) continue;
  const m = slugify(main);
  if (!entries.has(m)) entries.set(m, [m, main, '']);
  if (!sub) continue;
  const s = `${m}~${slugify(sub)}`;
  if (!entries.has(s)) entries.set(s, [s, sub, main]);
  // A sheet item equal to its sub is the sub itself (the app leaves it out too).
  if (!item || slugify(item) === slugify(sub)) continue;
  const l = `${s}~${slugify(item)}`;
  if (!entries.has(l)) entries.set(l, [l, item, `${main} > ${sub}`]);
}

const list = [...entries.values()];
const body = list.map((e) => `  ${JSON.stringify(e)},`).join('\n');
writeFileSync(
  TARGET,
  `// GENERATED by scripts/build-assistant-categories.mjs from packages/shared-client/data/category-taxonomy.csv
// - do not edit. ${list.length} categories: [taxo path, name, parent trail].
export const CATEGORY_INDEX: ReadonlyArray<readonly [taxo: string, name: string, parents: string]> = [
${body}
];
`,
);
console.log(`Wrote ${list.length} categories to ${path.relative(root, TARGET)}`);
